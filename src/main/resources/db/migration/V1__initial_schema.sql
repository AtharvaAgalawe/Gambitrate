CREATE TABLE player (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(50)  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_synced_at    TIMESTAMPTZ,
    last_synced_month VARCHAR(7),
    CONSTRAINT uq_player_username UNIQUE (username)
);

CREATE TABLE game (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chesscom_id       VARCHAR(255) NOT NULL,
    player_id         BIGINT       NOT NULL REFERENCES player (id) ON DELETE CASCADE,
    played_at         TIMESTAMPTZ  NOT NULL,
    time_class        VARCHAR(20)  NOT NULL,
    time_control      VARCHAR(32)  NOT NULL,
    base_seconds      INTEGER      NOT NULL CHECK (base_seconds >= 0),
    increment_seconds INTEGER      NOT NULL DEFAULT 0 CHECK (increment_seconds >= 0),
    color             VARCHAR(5)   NOT NULL CHECK (color IN ('white', 'black')),
    result            VARCHAR(8)   NOT NULL CHECK (result IN ('win', 'loss', 'draw')),
    termination       VARCHAR(16)  NOT NULL CHECK (termination IN (
        'checkmate', 'resign', 'timeout', 'abandoned', 'stalemate',
        'agreement', 'repetition', 'insufficient', 'other'
    )),
    player_rating     INTEGER,
    opponent_rating   INTEGER,
    eco_code          VARCHAR(8),
    opening_name      VARCHAR(255),
    moves_san         TEXT         NOT NULL,
    player_accuracy   NUMERIC(5, 2) CHECK (player_accuracy BETWEEN 0 AND 100),
    pgn               TEXT         NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_game_chesscom_id UNIQUE (chesscom_id)
);

CREATE TABLE move (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id             BIGINT  NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    ply                 INTEGER NOT NULL CHECK (ply > 0),
    san                 VARCHAR(16) NOT NULL,
    clock_remaining_ms  BIGINT CHECK (clock_remaining_ms >= 0),
    is_player_move      BOOLEAN NOT NULL,
    CONSTRAINT uq_move_game_ply UNIQUE (game_id, ply)
);

CREATE INDEX idx_game_player_played_at ON game (player_id, played_at);
CREATE INDEX idx_game_player_eco_color ON game (player_id, eco_code, color);
CREATE INDEX idx_game_player_time_class ON game (player_id, time_class);
