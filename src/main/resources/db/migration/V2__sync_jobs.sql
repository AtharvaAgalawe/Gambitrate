ALTER TABLE player
    ADD COLUMN last_game_end_time TIMESTAMPTZ;

CREATE TABLE sync_job (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id    BIGINT      NOT NULL REFERENCES player (id) ON DELETE CASCADE,
    status       VARCHAR(10) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'DONE', 'FAILED')),
    started_at   TIMESTAMPTZ,
    finished_at  TIMESTAMPTZ,
    months_total INTEGER     NOT NULL DEFAULT 0,
    months_done  INTEGER     NOT NULL DEFAULT 0,
    error        TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_sync_job_player_created
    ON sync_job (player_id, created_at DESC);

CREATE UNIQUE INDEX uq_sync_job_active
    ON sync_job (player_id)
    WHERE status IN ('QUEUED', 'RUNNING');
